#!/usr/bin/env python3
"""
Builds every app icon from src-tauri/icons/source/kai-brush.svg (the brush
改 on Kaizen's night ink, in the indigo-to-sunrise gradient).

  python3 scripts/make-icons.py

Needs rsvg-convert (brew install librsvg), iconutil (macOS) and pnpm. Writes:
the desktop and Windows icons (via `tauri icon`), a macOS icon with Apple's
margin, the Android adaptive icon (background, foreground, monochrome) and
legacy launcher PNGs, public/icon.png, and the in-app mark's path.
"""

import pathlib
import re
import shutil
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src-tauri/icons/source/kai-brush.svg"
RES = ROOT / "src-tauri/gen/android/app/src/main/res"
INK = "#13161e"
STOPS = [("0", "#8ea2f2"), ("0.55", "#a77bdc"), ("1", "#f0a03c")]

src = SOURCE.read_text()
PATH = re.search(r' d="([^"]+)"', src).group(1)
PATH_TRANSFORM = re.search(r'<path id="kai" transform="([^"]+)"', src).group(1)

GRADIENT = (
    '<linearGradient id="kai-g" x1="0" y1="0" x2="1" y2="1">'
    + "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in STOPS)
    + "</linearGradient>"
)


def glyph(cx, cy, size, fill="url(#kai-g)"):
    """The character centred on (cx, cy), `size` units per em."""
    k = size / 1000
    return f'<g transform="translate({cx} {cy}) scale({k})"><path transform="{PATH_TRANSFORM}" d="{PATH}" fill="{fill}"/></g>'


def svg(view, body):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}"><defs>{GRADIENT}</defs>{body}</svg>'


# Square, full bleed: Windows, Linux and the source for `tauri icon`.
FULL = svg("0 0 100 100", f'<rect width="100" height="100" fill="{INK}"/>{glyph(50, 51, 74)}')
# Rounded tile: favicon and legacy Android launchers.
TILE = svg("0 0 100 100", f'<rect width="100" height="100" rx="23" fill="{INK}"/>{glyph(50, 51, 74)}')
ROUND = svg("0 0 100 100", f'<circle cx="50" cy="50" r="50" fill="{INK}"/>{glyph(50, 51, 70)}')
# macOS: an 824 px rounded square inside 1024 with a soft shadow, as Apple's template has.
MAC = svg(
    "0 0 1024 1024",
    '<filter id="s" x="-10%" y="-10%" width="120%" height="125%"><feDropShadow dx="0" dy="10" stdDeviation="14" flood-opacity="0.32"/></filter>'
    f'<rect x="100" y="100" width="824" height="824" rx="185" fill="{INK}" filter="url(#s)"/>{glyph(512, 520, 610)}',
)
# Android adaptive icon layers (108 dp canvas, 66 dp safe circle).
FOREGROUND = svg("0 0 108 108", glyph(54, 54.5, 50))
MONOCHROME = svg("0 0 108 108", glyph(54, 54.5, 50, "#ffffff"))

DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}


def render(svg_text, out, size):
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), "-o", str(out)], input=svg_text.encode(), check=True)


with tempfile.TemporaryDirectory() as tmp:
    tmp = pathlib.Path(tmp)

    # Desktop and Windows sizes from the square source.
    render(FULL, tmp / "full.png", 1024)
    subprocess.run(["pnpm", "tauri", "icon", str(tmp / "full.png")], cwd=ROOT, check=True, stdout=subprocess.DEVNULL)

    # macOS icon with its margin and shadow.
    iconset = tmp / "kaizen.iconset"
    iconset.mkdir()
    for size in (16, 32, 128, 256, 512):
        render(MAC, iconset / f"icon_{size}x{size}.png", size)
        render(MAC, iconset / f"icon_{size}x{size}@2x.png", size * 2)
    subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(ROOT / "src-tauri/icons/icon.icns")], check=True)

    # Android: legacy PNGs and adaptive layers per density.
    for name, scale in DENSITIES.items():
        folder = RES / f"mipmap-{name}"
        render(TILE, folder / "ic_launcher.png", round(48 * scale))
        render(ROUND, folder / "ic_launcher_round.png", round(48 * scale))
        render(FOREGROUND, folder / "ic_launcher_foreground.png", round(108 * scale))
        render(MONOCHROME, folder / "ic_launcher_monochrome.png", round(108 * scale))

adaptive = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
"""
(RES / "mipmap-anydpi-v26").mkdir(exist_ok=True)
for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
    (RES / "mipmap-anydpi-v26" / name).write_text(adaptive)
(RES / "values/ic_launcher_background.xml").write_text(
    f'<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">{INK.upper()}</color>\n</resources>\n'
)

render(TILE, ROOT / "public/icon.png", 256)

# The in-app mark draws the same path.
(ROOT / "src/components/brandPath.ts").write_text(
    "// Generated by scripts/make-icons.py from src-tauri/icons/source/kai-brush.svg.\n"
    "/** 改 in brush script (Yuji Syuku, OFL), centred in a 1000-unit box around 0, 0. */\n"
    f'export const KAI_PATH = "{PATH}";\n'
    f'export const KAI_TRANSFORM = "{PATH_TRANSFORM}";\n'
)
print("icons written")
